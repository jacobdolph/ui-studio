/**
 * Decoder / encoder for Blizzard's Edit Mode layout export string — the text produced by
 * `C_EditMode.ConvertLayoutInfoToString` and consumed by `C_EditMode.ConvertStringToLayoutInfo`
 * (Edit Mode → Share → Export / Import Layout).
 *
 * The format is not documented by Blizzard; this implementation was derived from 570 real
 * exports (wago.io, 2022-2026, including WoW Forever beta builds) and cross-checked against the
 * FrameXML Lua in Gethe/wow-ui-source (branch `forever`). See FORMAT.md for the write-up.
 *
 * Grammar (all tokens whitespace-separated):
 *
 *   header  := <version> <numSystems>                          (version 0..3)
 *            | <version> <interfaceStyle> <numSystems>         (version >= 4, WoW Forever; 0=Mkb 1=Gamepad)
 *            | <version> <numSystems> <numSystems>             (live retail / Mists clients, Oct 2026)
 *   system  := <system> <systemIndex> <isInDefaultPosition> <anchor> <anchor2|-1> <settingsBlob>
 *   anchor  := <point> <relativePoint> <relativeTo> <offsetX> <offsetY>
 *
 *   systemIndex is 0-based in the string (Lua enums are 1-based); -1 for single-instance systems.
 *   point/relativePoint: 0 TOPLEFT 1 TOP 2 TOPRIGHT 3 LEFT 4 CENTER 5 RIGHT 6 BOTTOMLEFT 7 BOTTOM 8 BOTTOMRIGHT
 *   settingsBlob: "#" when empty, otherwise pairs of characters: chr(35+settingId) chr(35+value).
 *
 * A pre-release 2022 variant ("version 5" from the Dragonflight beta) drops isInDefaultPosition
 * and the anchor2 slot and puts a 0/1 flag after the anchor instead. It is decoded for
 * completeness but never produced.
 *
 * Everything needed for a byte-exact re-encode is preserved on the decoded object (raw offset
 * strings, raw header tokens, raw blobs), so decode→encode is lossless for every string we have
 * seen. Edited values are formatted the way the game formats them (one decimal place).
 */

export const ANCHOR_POINTS = [
  "TOPLEFT", "TOP", "TOPRIGHT",
  "LEFT", "CENTER", "RIGHT",
  "BOTTOMLEFT", "BOTTOM", "BOTTOMRIGHT",
] as const;
export type AnchorPoint = (typeof ANCHOR_POINTS)[number];

export const SETTING_CHAR_BASE = 35; // '#'
/**
 * Setting values are stored as little-endian base-90 digits. Each digit is its own
 * (settingId, digit) character pair, so a value >= 90 shows up as the same id twice in a row:
 * Opacity 100 → "7-7$" = (20,10)(20,1) = 10 + 1*90. Single-digit values use chars '#'..'|'.
 */
export const SETTING_DIGIT_BASE = 90;

export interface Anchor {
  point: AnchorPoint;
  relativeTo: string;
  relativePoint: AnchorPoint;
  offsetX: number;
  offsetY: number;
}

export interface SettingPair {
  /** Enum.EditMode<System>Setting value */
  id: number;
  /** Raw stored value (sliders store steps from min, see schema `convert`) */
  value: number;
  /**
   * Number of base-90 digit pairs the value occupied in the source string. Only set by the
   * decoder, only used to reproduce a string byte-for-byte (e.g. a redundant leading zero digit,
   * or a pre-2023 single char >= 90). Omit for values you create.
   */
  digits?: number;
}

export interface LayoutSystem {
  /** Enum.EditModeSystem */
  system: number;
  /** 1-based Lua systemIndex (Enum.EditMode<System>SystemIndices), or null for single-instance systems */
  systemIndex: number | null;
  isInDefaultPosition: boolean;
  anchor: Anchor;
  anchor2: Anchor | null;
  /** Ordered by id as the game writes them. One entry per setting id (multi-digit values are combined). */
  settings: SettingPair[];
  /** Raw tokens kept for exact round-tripping. Dropped automatically when values are edited via helpers. */
  raw?: {
    offsetX?: string;
    offsetY?: string;
    anchor2OffsetX?: string;
    anchor2OffsetY?: string;
    /** Original settings blob, kept when it cannot be regenerated byte-for-byte (odd length) */
    blob?: string;
  };
}

export type HeaderKind = "plain" | "style" | "dupCount";
export type Grammar = "modern" | "beta2022";

export interface Layout {
  /** First token. 0-2: retail/classic 2022-2026; 3-5: WoW Forever beta/launch builds. */
  version: number;
  /** Enum.InputDeviceInterfaceType (0 Mkb, 1 Gamepad). Only present in the `style` header (version >= 4). */
  interfaceStyle: number | null;
  headerKind: HeaderKind;
  grammar: Grammar;
  systems: LayoutSystem[];
  warnings: string[];
}

export class LayoutParseError extends Error {
  readonly tokenIndex: number | undefined;
  constructor(message: string, tokenIndex?: number) {
    super(message);
    this.name = "LayoutParseError";
    this.tokenIndex = tokenIndex;
  }
}

const INT = /^-?\d+$/;
const NUM = /^-?\d+(\.\d+)?$/;

export function tokenize(input: string): string[] {
  return input.trim().split(/[ \t\r\n]+/).filter((t) => t.length > 0);
}

function pointFromIndex(i: number, at: number): AnchorPoint {
  const p = ANCHOR_POINTS[i];
  if (!p) throw new LayoutParseError(`anchor point index ${i} out of range`, at);
  return p;
}
function pointToIndex(p: AnchorPoint): number {
  const i = ANCHOR_POINTS.indexOf(p);
  if (i < 0) throw new Error(`unknown anchor point ${p}`);
  return i;
}

export function decodeSettingsBlob(blob: string): { settings: SettingPair[]; odd: boolean; negative: boolean } {
  if (blob === "#") return { settings: [], odd: false, negative: false };
  const cps = Array.from(blob, (c) => c.codePointAt(0)! - SETTING_CHAR_BASE);
  const settings: SettingPair[] = [];
  let negative = false;
  for (let i = 0; i + 1 < cps.length; i += 2) {
    const id = cps[i], digit = cps[i + 1];
    if (id < 0 || digit < 0) negative = true;
    const prev = settings[settings.length - 1];
    if (prev && prev.id === id) {
      prev.value += digit * SETTING_DIGIT_BASE ** (prev.digits ?? 1);
      prev.digits = (prev.digits ?? 1) + 1;
    } else {
      settings.push({ id, value: digit, digits: 1 });
    }
  }
  return { settings, odd: cps.length % 2 === 1, negative };
}

function minimalDigits(value: number): number {
  let n = 1;
  for (let v = value; v >= SETTING_DIGIT_BASE; v = Math.floor(v / SETTING_DIGIT_BASE)) n++;
  return n;
}

export function encodeSettingsBlob(settings: SettingPair[]): string {
  if (settings.length === 0) return "#";
  let out = "";
  for (const s of settings) {
    if (!Number.isInteger(s.id) || s.id < 0) throw new Error(`invalid setting id ${s.id}`);
    if (!Number.isInteger(s.value) || s.value < 0) throw new Error(`invalid setting value ${s.value} for id ${s.id}`);
    // A decoder-provided digit count is reproduced exactly (the top digit absorbs the remainder).
    const n = s.digits ?? minimalDigits(s.value);
    let v = s.value;
    for (let k = 0; k < n; k++) {
      // The most significant digit absorbs any remainder so a forced digit count never loses data.
      const digit = k === n - 1 ? v : v % SETTING_DIGIT_BASE;
      out += String.fromCodePoint(SETTING_CHAR_BASE + s.id) + String.fromCodePoint(SETTING_CHAR_BASE + digit);
      v = Math.floor(v / SETTING_DIGIT_BASE);
    }
  }
  return out;
}

/** Format an offset the way the game does: one decimal place ("0.0", "-365.5"). */
export function formatOffset(n: number): string {
  if (!Number.isFinite(n)) throw new Error(`invalid offset ${n}`);
  const r = Math.round(n * 10) / 10;
  return (r === 0 ? 0 : r).toFixed(1);
}

interface Cursor { t: string[]; i: number }

function need(c: Cursor, what: string): string {
  if (c.i >= c.t.length) throw new LayoutParseError(`unexpected end of string, expected ${what}`, c.i);
  return c.t[c.i++];
}
function needInt(c: Cursor, what: string): number {
  const at = c.i;
  const s = need(c, what);
  if (!INT.test(s)) throw new LayoutParseError(`expected integer for ${what}, got "${s}"`, at);
  return parseInt(s, 10);
}
function needNum(c: Cursor, what: string): string {
  const at = c.i;
  const s = need(c, what);
  if (!NUM.test(s)) throw new LayoutParseError(`expected number for ${what}, got "${s}"`, at);
  return s;
}

function readAnchor(c: Cursor, sys: LayoutSystem, secondary: boolean): Anchor {
  const at = c.i;
  const point = pointFromIndex(needInt(c, "point"), at);
  const relativePoint = pointFromIndex(needInt(c, "relativePoint"), at);
  const relativeTo = need(c, "relativeTo");
  if (NUM.test(relativeTo)) throw new LayoutParseError(`expected frame name for relativeTo, got "${relativeTo}"`, c.i - 1);
  const ox = needNum(c, "offsetX");
  const oy = needNum(c, "offsetY");
  sys.raw ??= {};
  if (secondary) { sys.raw.anchor2OffsetX = ox; sys.raw.anchor2OffsetY = oy; }
  else { sys.raw.offsetX = ox; sys.raw.offsetY = oy; }
  return { point, relativeTo, relativePoint, offsetX: parseFloat(ox), offsetY: parseFloat(oy) };
}

function readSystems(c: Cursor, grammar: Grammar, warnings: string[]): LayoutSystem[] {
  const systems: LayoutSystem[] = [];
  while (c.i < c.t.length) {
    const at = c.i;
    const system = needInt(c, "system");
    const idx = needInt(c, "systemIndex");
    const sys: LayoutSystem = {
      system,
      systemIndex: idx < 0 ? null : idx + 1,
      isInDefaultPosition: false,
      anchor: null as unknown as Anchor,
      anchor2: null,
      settings: [],
    };
    if (system < 0) throw new LayoutParseError(`negative system id at token ${at}`, at);
    if (grammar === "modern") {
      const d = needInt(c, "isInDefaultPosition");
      if (d !== 0 && d !== 1) throw new LayoutParseError(`isInDefaultPosition must be 0/1, got ${d}`, c.i - 1);
      sys.isInDefaultPosition = d === 1;
      sys.anchor = readAnchor(c, sys, false);
      const slot = need(c, "anchor2 or -1");
      if (slot !== "-1") {
        c.i--; // the slot is the start of a second anchor
        sys.anchor2 = readAnchor(c, sys, true);
      }
    } else {
      sys.anchor = readAnchor(c, sys, false);
      const d = needInt(c, "isInDefaultPosition");
      if (d !== 0 && d !== 1) throw new LayoutParseError(`flag must be 0/1, got ${d}`, c.i - 1);
      sys.isInDefaultPosition = d === 1;
    }
    const blob = need(c, "settings");
    const { settings, odd, negative } = decodeSettingsBlob(blob);
    sys.settings = settings;
    if (odd || negative) {
      sys.raw ??= {};
      sys.raw.blob = blob;
      warnings.push(`system ${system}/${idx}: malformed settings blob (${odd ? "odd length" : "character below '#'"}); kept verbatim`);
    }
    systems.push(sys);
  }
  return systems;
}

interface Candidate { headerLen: number; headerKind: HeaderKind; grammar: Grammar }

/**
 * Decode an Edit Mode export string. Throws LayoutParseError when the text is not a layout string.
 */
export function decodeLayoutString(input: string): Layout {
  const t = tokenize(input);
  if (t.length < 3) throw new LayoutParseError("too short to be an Edit Mode layout string");
  if (!INT.test(t[0])) throw new LayoutParseError(`expected version number, got "${t[0]}"`, 0);
  const version = parseInt(t[0], 10);
  if (version < 0 || version > 99) throw new LayoutParseError(`implausible version ${version}`, 0);

  const candidates: Candidate[] = [];
  const t1 = INT.test(t[1]) ? parseInt(t[1], 10) : NaN;
  const t2 = INT.test(t[2]) ? parseInt(t[2], 10) : NaN;
  // Forever (>=4): "<ver> <style> <count>". Live Oct-2026 clients: "<ver> <count> <count>".
  if (version >= 4 && (t1 === 0 || t1 === 1)) candidates.push({ headerLen: 3, headerKind: "style", grammar: "modern" });
  candidates.push({ headerLen: 2, headerKind: "plain", grammar: "modern" });
  if (t1 === t2 && t1 > 1) candidates.push({ headerLen: 3, headerKind: "dupCount", grammar: "modern" });
  if (version >= 4 && !(t1 === 0 || t1 === 1)) candidates.push({ headerLen: 3, headerKind: "style", grammar: "modern" });
  candidates.push({ headerLen: 2, headerKind: "plain", grammar: "beta2022" });

  const errors: string[] = [];
  for (const cand of candidates) {
    const warnings: string[] = [];
    const countTok = t[cand.headerLen - 1];
    if (!INT.test(countTok)) { errors.push(`${cand.headerKind}/${cand.grammar}: count "${countTok}" not an integer`); continue; }
    const count = parseInt(countTok, 10);
    try {
      const systems = readSystems({ t, i: cand.headerLen }, cand.grammar, warnings);
      if (systems.length !== count) throw new LayoutParseError(`header says ${count} systems, found ${systems.length}`);
      let interfaceStyle: number | null = null;
      if (cand.headerKind === "style") interfaceStyle = t1;
      if (cand.grammar === "beta2022") warnings.push("pre-release (2022 beta) field order; decode only");
      return { version, interfaceStyle, headerKind: cand.headerKind, grammar: cand.grammar, systems, warnings };
    } catch (e) {
      errors.push(`${cand.headerKind}/${cand.grammar}: ${(e as Error).message}`);
    }
  }
  throw new LayoutParseError(`not a recognized Edit Mode layout string (${errors.join("; ")})`);
}

export interface EncodeOptions {
  /** Force a header shape. Default: the one the layout was decoded with (or `style` for version >= 4, else `plain`). */
  headerKind?: HeaderKind;
}

/** Encode a Layout back to the game's text format. Lossless for anything produced by decodeLayoutString. */
export function encodeLayoutString(layout: Layout, opts: EncodeOptions = {}): string {
  const out: string[] = [String(layout.version)];
  const count = String(layout.systems.length);
  const headerKind = opts.headerKind ?? layout.headerKind ?? (layout.version >= 4 ? "style" : "plain");
  if (headerKind === "style") out.push(String(layout.interfaceStyle ?? 0), count);
  else if (headerKind === "dupCount") out.push(count, count);
  else out.push(count);

  for (const s of layout.systems) {
    out.push(String(s.system), String(s.systemIndex === null ? -1 : s.systemIndex - 1));
    const pushAnchor = (a: Anchor, rawX?: string, rawY?: string) => {
      out.push(String(pointToIndex(a.point)), String(pointToIndex(a.relativePoint)), a.relativeTo);
      out.push(rawX !== undefined && parseFloat(rawX) === a.offsetX ? rawX : formatOffset(a.offsetX));
      out.push(rawY !== undefined && parseFloat(rawY) === a.offsetY ? rawY : formatOffset(a.offsetY));
    };
    if (layout.grammar === "modern") {
      out.push(s.isInDefaultPosition ? "1" : "0");
      pushAnchor(s.anchor, s.raw?.offsetX, s.raw?.offsetY);
      if (s.anchor2) pushAnchor(s.anchor2, s.raw?.anchor2OffsetX, s.raw?.anchor2OffsetY);
      else out.push("-1");
    } else {
      pushAnchor(s.anchor, s.raw?.offsetX, s.raw?.offsetY);
      out.push(s.isInDefaultPosition ? "1" : "0");
    }
    out.push(s.raw?.blob !== undefined && settingsUntouched(s) ? s.raw.blob : encodeSettingsBlob(s.settings));
  }
  return out.join(" ");
}

function settingsUntouched(sys: LayoutSystem): boolean {
  if (sys.raw?.blob === undefined) return false;
  const orig = decodeSettingsBlob(sys.raw.blob).settings;
  return orig.length === sys.settings.length && orig.every((p, i) => sys.settings[i].id === p.id && sys.settings[i].value === p.value);
}

/** Look up a setting's raw value. */
export function getSetting(sys: LayoutSystem, id: number): number | undefined {
  return sys.settings.find((s) => s.id === id)?.value;
}

/** Set a setting's raw value (appends, keeping ids sorted, when missing). Drops round-trip raw data for the blob. */
export function setSetting(sys: LayoutSystem, id: number, value: number): void {
  const existing = sys.settings.find((s) => s.id === id);
  if (existing) { existing.value = value; delete existing.digits; }
  else {
    sys.settings.push({ id, value });
    sys.settings.sort((a, b) => a.id - b.id);
  }
  if (sys.raw) delete sys.raw.blob;
}

/** Create the minimal, canonical structure for a fresh WoW Forever layout. */
export function createLayout(systems: LayoutSystem[], opts: { version?: number; interfaceStyle?: number } = {}): Layout {
  return {
    version: opts.version ?? 5,
    interfaceStyle: opts.interfaceStyle ?? 0,
    headerKind: "style",
    grammar: "modern",
    systems,
    warnings: [],
  };
}
